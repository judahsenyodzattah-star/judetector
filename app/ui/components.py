"""Reusable interface primitives — the proof-sheet vocabulary.

A page is assembled from a handful of pieces: a page head, a section rule, a
mounted print with a caption strip, a fixed-column readout, a flow rule, a note, an
empty state, steps, bullets and the footer. There are no cards, no pills, no icon
set, and no tinted panels; hierarchy comes from type size, alignment and hairlines.

Monospace is reserved for facts: file names, dimensions, counts, confidences,
thresholds. Prose is never set in it.

Any dynamic value interpolated into HTML is escaped; the only unescaped input is
markup this package generates itself.
"""

from __future__ import annotations

from collections.abc import Sequence
from html import escape

import streamlit as st

__all__ = [
    "bullets",
    "caption_strip",
    "display_headline",
    "empty_state",
    "flow_line",
    "footer",
    "meta",
    "note",
    "page_header",
    "plate",
    "plate_label",
    "readout",
    "section",
    "steps",
]


def _html(markup: str) -> None:
    st.markdown(markup, unsafe_allow_html=True)


# --------------------------------------------------------------------------
# Heads and sections
# --------------------------------------------------------------------------
def page_header(title: str, subtitle: str | None = None) -> None:
    """Page title plus one supporting line."""
    subtitle_html = f'<p class="jd-sub">{escape(subtitle)}</p>' if subtitle else ""
    _html(
        '<div class="jd-head">'
        f'<h1 class="jd-h1">{escape(title)}</h1>'
        f"{subtitle_html}"
        "</div>"
    )


def display_headline(title: str, intro: str) -> None:
    """Landing headline with a single supporting sentence."""
    _html(
        f'<h1 class="jd-display">{escape(title)}</h1>'
        f'<p class="jd-intro">{escape(intro)}</p>'
    )


def section(title: str, subtitle: str | None = None) -> None:
    """Section heading: a hairline, a title, an optional line. Never a card."""
    sub = f'<p class="jd-section__sub">{escape(subtitle)}</p>' if subtitle else ""
    _html(
        '<div class="jd-section">'
        f'<h2 class="jd-section__title">{escape(title)}</h2>{sub}'
        "</div>"
    )


# --------------------------------------------------------------------------
# Prints
# --------------------------------------------------------------------------
def plate(art: str, *, label: str) -> None:
    """A mounted print: white mount, hairline registration marks, a caption label.

    `art` is trusted inline SVG generated by this package; `label` is escaped text.
    """
    _html(
        '<figure class="jd-plate">'
        f'<div class="jd-plate__art">{art}</div>'
        f'<figcaption class="jd-plate-label">{escape(label)}</figcaption>'
        "</figure>"
    )


def plate_label(label: str) -> None:
    """Caption for an image rendered by `st.image`, which cannot carry one itself."""
    _html(f'<p class="jd-plate-label">{escape(label)}</p>')


def caption_strip(fields: Sequence[tuple[str, str]]) -> None:
    """State the facts about a print: ``FILE sample.png · FRAME 1024×768``.

    Only real values belong here. If there is nothing to state, render nothing.
    """
    rendered = "".join(
        '<span class="jd-caption__field">'
        f'<span class="jd-caption__label">{escape(label)}</span>'
        f'<span class="jd-caption__value">{escape(value)}</span>'
        "</span>"
        for label, value in fields
    )
    _html(f'<div class="jd-caption">{rendered}</div>')


def readout(rows: Sequence[tuple[str, str]]) -> None:
    """Fixed-column numeric readout: label left, mono value right, aligned."""
    rendered = "".join(
        f'<span class="jd-readout__label">{escape(label)}</span>'
        f'<span class="jd-readout__value">{escape(value)}</span>'
        for label, value in rows
    )
    _html(f'<div class="jd-readout">{rendered}</div>')


def flow_line(stations: Sequence[str]) -> None:
    """The workflow as stations on one rule. Says the flow once, then stops."""
    rendered = "".join(f"<span>{escape(station)}</span>" for station in stations)
    _html(f'<p class="jd-flow">{rendered}</p>')


# --------------------------------------------------------------------------
# Text pieces
# --------------------------------------------------------------------------
def note(text: str, *, tone: str = "info") -> None:
    """Quiet inline notice: a rule and a sentence, never a banner or a colour block."""
    tone_css = "jd-note--warn" if tone == "warn" else ""
    _html(f'<div class="jd-note {tone_css}">{escape(text)}</div>')


def empty_state(*, title: str, body: str) -> None:
    """Left-aligned statement of what is missing and what to do next."""
    _html(
        '<div class="jd-empty">'
        f'<p class="jd-empty__title">{escape(title)}</p>'
        f'<p class="jd-empty__body">{escape(body)}</p>'
        "</div>"
    )


def steps(items: Sequence[tuple[str, str]]) -> None:
    """Ordered ``(title, body)`` steps; numbering is real, not decoration."""
    rendered = "".join(
        '<div class="jd-step">'
        f'<div class="jd-step__num">{index}</div>'
        f'<div class="jd-step__body"><b>{escape(title)}</b><span>{escape(body)}</span></div>'
        "</div>"
        for index, (title, body) in enumerate(items, start=1)
    )
    _html(f'<div class="jd-steps">{rendered}</div>')


def bullets(items: Sequence[str]) -> None:
    """Tight bulleted list for limits and privacy notes."""
    rendered = "".join(f"<li>{escape(item)}</li>" for item in items)
    _html(f'<ul class="jd-list">{rendered}</ul>')


def meta(text: str) -> None:
    """One line of real context under a component (formats, limits, sizes)."""
    _html(f'<p class="jd-meta">{escape(text)}</p>')


# --------------------------------------------------------------------------
# Footer
# --------------------------------------------------------------------------
def footer(note: str, *, page, page_label: str = "Help") -> None:
    """Single-row footer: wordmark, one privacy line, one real page link.

    The link is rendered with `st.page_link`, so it is a genuine anchor rather than
    raw HTML.
    """
    text_column, link_column = st.columns([5, 1], gap="small", vertical_alignment="center")
    with text_column:
        _html(
            '<div class="jd-footer">'
            '<p class="jd-footer__brand">JUDEtector</p>'
            f'<p class="jd-footer__note">{escape(note)}</p>'
            "</div>"
        )
    with link_column:
        st.page_link(page, label=page_label, icon=None)
